"""Per-step readiness for the guided workflow. WORKSPACE_FLOW_NAV_PLAN §8.3, P3.

What this is for
-----------------
The rail shows 17 numbered steps and the strip above it shows how far along the
work is. Both need the same answer: for each step, is its work done, and if not,
why not. Answering that per page meant each page inventing its own notion of
"done", which is how the old rail ended up unable to say anything at all.

So the step -> prerequisite mapping lives **here**, on the backend, next to the
predicates that evaluate it. The frontend registry holds presentation metadata
(`type`, `step`, `needs`, `tabs`); it holds no knowledge of how completion is
determined, so the two cannot disagree.

Design constraints, both from the owner
--------------------------------------
* **Sequence, never enforce.** A step that is not done is still reachable, still
  rendered, still clickable. This module reports; it does not gate. Nothing here
  returns a 403, and no caller may treat "not done" as a reason to refuse.
* **Flag, do not block.** Staleness is reported alongside completion. Editing the
  map after a sampling design exists does not invalidate anything on its own; it
  tells the user their design predates the map.

Reuses :mod:`prereq_check` rather than reimplementing completion. Its
``PrereqResult`` is already bilingual and three-state, so a step's reason and hint
come back ready to render in either language.
"""
from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional
from uuid import UUID

from sqlalchemy.orm import Session

from .prereq_check import check

logger = logging.getLogger(__name__)

# Step id -> the prerequisite tags that decide whether it is done.
#
# Ids match the frontend registry (`components/calculation/calcContexts.ts`). The
# two are checked against each other by
# `frontend/src/components/calculation/__tests__/workflowReadiness.test.ts`, so a
# step added to the registry without a rule here fails rather than silently
# reporting "not done" forever.
#
# A step mapped to an empty tuple is one whose completion cannot be determined
# from the database — `detaildescription` is autogenerated from whatever the
# analysis pages produced, so it is "done" as soon as the forest has inventory
# data, and the honest answer is the inventory's.
STEP_PREREQS: Dict[str, tuple[str, ...]] = {
    # 1 — the map gates everything, so its rule is its own predicate (D11).
    "unified": ("map_complete",),
    # 2 — the user group's boundary, its household data (a list OR totals) and its executive committee are all mandatory
    # (owner, 2026-10-11); the advisory and financial committees are optional and not tracked.
    "usergroup": ("user_group_extent", "household_data", "executive_committee"),
    # 3 — a field instrument, generated from the map and printed before going out.
    "fieldbook": ("fieldbook",),
    # 4 — designed from the map.
    "sampling": ("sampling",),
    # 5 — the visit that also collects forest metadata.
    "fieldinventory": ("field_inventory",),
    # 6 — the forest's own record (names, code, financial year); a step of its own since 2026-10-11.
    "forestmetadata": ("forest_metadata",),
    # 7 — species recorded on the same plots.
    "biodiversity": ("biodiversity_data",),
    # 8 — stems mapped after the forest inventory exists.
    "treemapping": ("tree_mapping",),
    # 9 — the NTFP resource survey: an OPTIONAL step (owner, 2026-10-22). Done when records have been brought in; a saved design alone is only a plan.
    "ntfp": ("ntfp_survey",),
    # 10 — autogenerated (D14); ready once there is something to describe.
    "detaildescription": ("field_inventory",),
    # 11 — area tables are derived from the boundary and sub-areas.
    "areadetail": ("sub_areas",),
    # off the numbered steps (Advanced) — zonal stats need the national DEM to cover the forest.
    "analysis": ("raster_zonal",),
    # off the numbered steps (Advanced) — the RUSLE soil-loss map needs soil-grid coverage.
    "hazarderosion": ("soil_data",),
    # 12 — the SFM classification must have been built.
    "sustainablefm": ("sfm_data",),
    # 13 — done when the base scenario has a calculated result: the same rule the export gate uses (owner, 2026-10-16;
    # it used to turn green as soon as an inventory existed).
    "cba": ("cba_calculated",),
    # 14 — the yearly activities: done only when the owner says so (2026-10-15); a later change reopens it.
    "yearly": ("yearly_activities_done",),
    # 15 — desktop work, and only meaningful once activities exist AND at least
    # one carries a drawn feature.
    "mgmtplan": ("proposed_activities", "activity_drawn_features"),
    # 16 — the terminal deliverable.
    "issuesubmit": ("plan_submitted",),
}

# Steps with no database-detectable completion. The Trial page is the only one: it
# is optional, so "done" is not a state the workflow waits for.
NON_TRACKED = ("treemodel",)


def _current_geometry_version(db: Session, calculation_id: UUID) -> Optional[int]:
    from app.models.calculation import Calculation

    try:
        return (
            db.query(Calculation.geometry_version)
            .filter(Calculation.id == calculation_id)
            .scalar()
        )
    except Exception:  # noqa: BLE001
        logger.exception("workflow_readiness: could not read geometry_version")
        return None


def step_readiness(
    db: Optional[Session], calculation_id: Optional[UUID]
) -> Dict[str, Dict[str, Any]]:
    """Per-step completion, keyed by the frontend's context id.

    Each entry: ``{done, status, reason_en, reason_ne, hint_en, hint_ne}``.
    ``status`` is the underlying :class:`PrereqResult` status, so a step blocked
    by a capability the system does not have (``unavailable``) is distinguishable
    from one waiting on data (``partial``) — the first is not the user's fault
    and not worth nagging about.
    """
    out: Dict[str, Dict[str, Any]] = {}
    for step_id, tags in STEP_PREREQS.items():
        result = check(db, calculation_id, list(tags))
        out[step_id] = {
            "done": result.met,
            "status": result.status,
            "reason_en": result.reason_en,
            "reason_ne": result.reason_ne,
            "hint_en": result.hint_en,
            "hint_ne": result.hint_ne,
        }
    return out


def workflow_readiness(
    db: Session, calculation_id: UUID
) -> Dict[str, Any]:
    """The whole strip's worth of state, in one call.

    The clock is read FIRST, then the steps. That order is load-bearing: several
    prerequisite predicates issue raw SQL against national tables that may be
    absent on a given deployment (`rasters.dem`, `base.mmu` / `soil.soilgrids`,
    `geology.geology`), and a failed statement aborts the transaction, after
    which every later query fails with `InFailedSqlTransaction`. Reading the clock
    afterwards returned `None` on exactly the deployments where the reading matters
    most. `prereq_check.check` now runs each predicate inside a savepoint, which
    isolates the tags from each other; reading the clock first isolates the one
    value that has no predicate to shield it.
    """
    geometry_version = _current_geometry_version(db, calculation_id)
    steps = step_readiness(db, calculation_id)
    done = [sid for sid, s in steps.items() if s["done"]]
    map_step = steps.get("unified", {})
    return {
        "geometry_version": geometry_version,
        "map_finished": bool(map_step.get("done")),
        "steps": steps,
        "done_count": len(done),
        "tracked_count": len(STEP_PREREQS),
        "non_tracked": list(NON_TRACKED),
    }


def step_flags(
    readiness: Dict[str, Any], seen_geometry_versions: Dict[str, int]
) -> List[Dict[str, str]]:
    """Steps whose completion predates a later geometry change.

    ``seen_geometry_versions`` maps step id -> the ``geometry_version`` the client
    recorded when it last saw that step done. A step is stale when the current
    version is higher. Pure and client-fed so it is trivially testable, and so the
    backend does not need to know when the client last looked.
    """
    current = readiness.get("geometry_version")
    if current is None:
        return []
    flags: List[Dict[str, str]] = []
    for step_id, seen in seen_geometry_versions.items():
        state = readiness.get("steps", {}).get(step_id)
        if not state or not state.get("done"):
            continue  # not done yet, so nothing to be stale *relative to*
        if current > seen:
            flags.append({"step": step_id, "reason": "geometry_changed", "seen": str(seen)})
    return flags
