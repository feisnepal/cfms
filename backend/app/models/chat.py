"""Chatbot tables (``CHATBOT_PLAN.md`` section 4, migration 147).

No column or foreign key here points at a forest or a calculation: a deleted forest leaves no chat row behind and none can block it.
"""
from sqlalchemy import (
    Boolean, CheckConstraint, Column, Computed, Date, DateTime, ForeignKey, Index, Integer, SmallInteger, String, Text, UUID, func, text,
)
from sqlalchemy.dialects.postgresql import ARRAY, TSVECTOR

from ..core.database import Base

CHAT_STATUS_REQUESTED = "requested"
CHAT_STATUS_APPROVED = "approved"
CHAT_STATUS_REVOKED = "revoked"
DEFAULT_DAILY_CAP_TOKENS = 100_000  # D10 (super admins: 500,000)


class ChatAccess(Base):
    __tablename__ = "chat_access"
    __table_args__ = (
        CheckConstraint("status IN ('requested','approved','revoked')", name="ck_chat_access_status"),
        CheckConstraint("daily_cap_tokens >= 0", name="ck_chat_access_cap"),
        Index("ix_chat_access_status", "status"),
    )
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    status = Column(String(10), nullable=False, server_default=CHAT_STATUS_REQUESTED)
    daily_cap_tokens = Column(Integer, nullable=False, server_default=str(DEFAULT_DAILY_CAP_TOKENS))
    plan = Column(String(20), nullable=False, server_default="approved")  # later: free / paid (D7), no payment code now
    requested_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    request_note = Column(Text, nullable=True)
    approved_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    approved_at = Column(DateTime(timezone=True), nullable=True)
    expires_at = Column(DateTime(timezone=True), nullable=True)
    revoked_at = Column(DateTime(timezone=True), nullable=True)


class ChatUsage(Base):
    __tablename__ = "chat_usage"
    __table_args__ = (
        CheckConstraint("tokens_in >= 0 AND tokens_out >= 0 AND reserved >= 0 AND messages >= 0", name="ck_chat_usage_nonneg"),
        Index("ix_chat_usage_day", "day"),
    )
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    day = Column(Date, primary_key=True)
    tokens_in = Column(Integer, nullable=False, server_default="0")
    tokens_out = Column(Integer, nullable=False, server_default="0")
    reserved = Column(Integer, nullable=False, server_default="0")  # reserve-then-settle hold (R2)
    messages = Column(Integer, nullable=False, server_default="0")
    updated_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ChatMessage(Base):
    __tablename__ = "chat_messages"
    __table_args__ = (
        CheckConstraint("role IN ('user','assistant','tool')", name="ck_chat_message_role"),
        CheckConstraint("feedback IS NULL OR feedback IN (-1, 1)", name="ck_chat_message_feedback"),
        Index("ix_chat_messages_user_created", "user_id", "created_at"),
        Index("ix_chat_messages_session_created", "session_id", "created_at"),
        Index("ix_chat_messages_unpurged", "created_at", postgresql_where=text("content IS NOT NULL")),
        Index("ix_chat_messages_feedback", "created_at", postgresql_where=text("feedback = -1")),
    )
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    session_id = Column(UUID(as_uuid=True), nullable=False)
    role = Column(String(10), nullable=False)
    content = Column(Text, nullable=True)  # nulled after 30 days (D11); counters stay
    tool_names = Column(ARRAY(String(60)), nullable=False, server_default="{}")
    provider = Column(String(30), nullable=True)
    model = Column(String(80), nullable=True)
    tokens_in = Column(Integer, nullable=False, server_default="0")
    tokens_out = Column(Integer, nullable=False, server_default="0")
    feedback = Column(SmallInteger, nullable=True)  # -1 thumbs down, 1 thumbs up
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    content_purged_at = Column(DateTime(timezone=True), nullable=True)


class ChatHelpChunk(Base):
    """A passage of help text (a fact card, later an accepted forum answer or guideline text). ``search_vector`` is generated by the database."""
    __tablename__ = "chat_help_chunks"
    __table_args__ = (
        CheckConstraint("source IN ('card','forum','guideline')", name="ck_chat_help_source"),
        Index("ix_chat_help_search", "search_vector", postgresql_using="gin"),
        Index("ix_chat_help_source_active", "source", "active"),
    )
    id = Column(String(80), primary_key=True)
    source = Column(String(12), nullable=False, server_default="card")
    source_ref = Column(Text, nullable=True)
    title = Column(Text, nullable=False)
    title_ne = Column(Text, nullable=True)
    body = Column(Text, nullable=False)
    keywords = Column(Text, nullable=False, server_default="")
    steps = Column(ARRAY(String(40)), nullable=False, server_default="{}")
    active = Column(Boolean, nullable=False, server_default="true")
    updated_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    search_vector = Column(
        TSVECTOR,
        Computed(
            "setweight(to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(title_ne, '') || ' ' || keywords), 'A') || "
            "setweight(to_tsvector('simple', body), 'B')",
            persisted=True,
        ),
    )


class ChatSettings(Base):
    """One row, id = 1: the kill switch and the daily ceiling shared by all users (R3)."""
    __tablename__ = "chat_settings"
    __table_args__ = (CheckConstraint("id = 1", name="ck_chat_settings_single_row"),)
    id = Column(SmallInteger, primary_key=True)
    enabled = Column(Boolean, nullable=False, server_default="true")
    pool_daily_tokens = Column(Integer, nullable=True)
    updated_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    updated_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
