"""Community Q&A forum tables (``FORUM_SPEC.md`` section 2).

One ``forum_posts`` table holds questions, answers and comments. Every vote, flag, accept and close is a row in ``forum_actions`` that
can be cancelled; reputation is the sum of ``forum_reputation_events`` (``app/services/forum/ledger.py``).

A post carries NO forest link: the forest-delete rule makes every foreign key to ``calculations`` cascade, and a question must outlive a
forest (an exception would be an owner decision). It carries the workflow step it was asked from instead.
"""
from sqlalchemy import (
    Boolean, CheckConstraint, Column, Computed, DateTime, Float, ForeignKey, Index, Integer, String, Text, UniqueConstraint, UUID, func, text,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import relationship

from ..core.database import Base


class ForumProfile(Base):
    __tablename__ = "forum_profiles"
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    reputation = Column(Integer, nullable=False, server_default="0")  # cache of sum(forum_reputation_events.value)
    about = Column(Text, nullable=True)
    is_moderator = Column(Boolean, nullable=False, server_default="false")
    last_seen = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ForumPost(Base):
    __tablename__ = "forum_posts"
    __table_args__ = (
        CheckConstraint("kind IN ('question','answer','comment')", name="ck_forum_post_kind"),
        CheckConstraint("closed_reason IS NULL OR closed_reason IN ('duplicate','off_topic','resolved')", name="ck_forum_post_closed_reason"),
        Index("ix_forum_posts_kind_activity", "kind", "last_activity_at"),
        Index("ix_forum_posts_kind_created", "kind", "created_at"),
        Index("ix_forum_posts_kind_score", "kind", "score"),
        Index("ix_forum_posts_parent_kind", "parent_id", "kind"),
        Index("ix_forum_posts_author_kind_created", "author_id", "kind", "created_at"),
        # at most one accepted answer per question
        Index("uq_forum_posts_one_accepted", "root_id", unique=True, postgresql_where=text("accepted_at IS NOT NULL")),
    )
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    kind = Column(String(10), nullable=False)
    parent_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), nullable=True)
    root_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), nullable=True)  # the question; null for a question
    # an author who deletes their account keeps the post as "former member"
    author_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    title = Column(String(300), nullable=True)  # questions only
    body_md = Column(Text, nullable=False)      # the markdown source; HTML is rendered on read, never stored as the truth
    workflow_step = Column(String(40), nullable=True)  # the numbered step the question was asked from
    score = Column(Integer, nullable=False, server_default="0")
    answer_count = Column(Integer, nullable=False, server_default="0")
    comment_count = Column(Integer, nullable=False, server_default="0")
    view_count = Column(Integer, nullable=False, server_default="0")
    flag_count = Column(Integer, nullable=False, server_default="0")
    active_revision = Column(Integer, nullable=False, server_default="1")
    accepted_at = Column(DateTime(timezone=True), nullable=True)
    closed_at = Column(DateTime(timezone=True), nullable=True)
    closed_reason = Column(String(10), nullable=True)
    duplicate_of_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="SET NULL"), nullable=True)
    pending_review = Column(Boolean, nullable=False, server_default="false")
    deleted_at = Column(DateTime(timezone=True), nullable=True)
    deleted_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    last_activity_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    last_activity_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    # generated by the database (migration 144); 'simple' keeps Devanagari as written
    search_vector = Column(TSVECTOR, Computed("to_tsvector('simple', coalesce(title, '') || ' ' || body_md)", persisted=True))

    revisions = relationship("ForumPostRevision", back_populates="post", cascade="all, delete-orphan", passive_deletes=True)


class ForumPostRevision(Base):
    __tablename__ = "forum_post_revisions"
    __table_args__ = (UniqueConstraint("post_id", "revision", name="uq_forum_post_revision"),)
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    post_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), nullable=False)
    revision = Column(Integer, nullable=False)
    title = Column(String(300), nullable=True)
    body_md = Column(Text, nullable=False)
    tag_names = Column(String(200), nullable=True)  # space separated, as written at this revision
    summary = Column(String(300), nullable=True)
    author_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    revised_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())

    post = relationship("ForumPost", back_populates="revisions")


class ForumTag(Base):
    __tablename__ = "forum_tags"
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    name = Column(String(80), nullable=False, unique=True)  # lowercase
    description_md = Column(Text, nullable=True)
    used_count = Column(Integer, nullable=False, server_default="0")  # posts that count (not deleted, not held); never below 0
    created_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ForumPostTag(Base):
    __tablename__ = "forum_post_tags"
    post_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), primary_key=True)
    tag_id = Column(UUID(as_uuid=True), ForeignKey("forum_tags.id", ondelete="CASCADE"), primary_key=True)


class ForumTagSynonym(Base):
    __tablename__ = "forum_tag_synonyms"
    source_name = Column(String(80), primary_key=True)
    tag_id = Column(UUID(as_uuid=True), ForeignKey("forum_tags.id", ondelete="CASCADE"), nullable=False)
    created_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ForumTagMark(Base):
    __tablename__ = "forum_tag_marks"
    __table_args__ = (CheckConstraint("reason IN ('interesting','ignored')", name="ck_forum_tag_mark_reason"),)
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    tag_id = Column(UUID(as_uuid=True), ForeignKey("forum_tags.id", ondelete="CASCADE"), primary_key=True)
    reason = Column(String(12), nullable=False)


class ForumAction(Base):
    """Everything a user does to a post: vote, flag, favourite, accept, close, delete. Cancelling undoes it and its reputation."""
    __tablename__ = "forum_actions"
    __table_args__ = (
        CheckConstraint(
            "action_type IN ('vote_up','vote_down','accept','flag','favorite','close','delete')", name="ck_forum_action_type",
        ),
        # one live vote / flag / favourite per user per post; a vote may be cancelled and cast again
        Index(
            "uq_forum_actions_live_single", "user_id", "post_id", "action_type", unique=True,
            postgresql_where=text("canceled_at IS NULL AND action_type IN ('vote_up','vote_down','flag','favorite')"),
        ),
        Index("ix_forum_actions_post", "post_id", "action_type"),
        Index("ix_forum_actions_user_date", "user_id", "created_at"),
    )
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    post_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), nullable=False)
    action_type = Column(String(12), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    canceled_at = Column(DateTime(timezone=True), nullable=True)
    canceled_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)


class ForumReputationEvent(Base):
    """One change to one user's reputation. ``value`` is the amount actually applied (after the clamp at 0), so a cancel can reverse it exactly."""
    __tablename__ = "forum_reputation_events"
    __table_args__ = (Index("ix_forum_rep_user", "user_id", "created_at"),)
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    action_id = Column(UUID(as_uuid=True), ForeignKey("forum_actions.id", ondelete="CASCADE"), nullable=True)
    value = Column(Integer, nullable=False)
    by_cancel = Column(Boolean, nullable=False, server_default="false")
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ForumFlag(Base):
    """A user's report of a post. A flag never hides or deletes anything by itself; a moderator resolves it."""
    __tablename__ = "forum_flags"
    __table_args__ = (
        CheckConstraint("resolution IS NULL OR resolution IN ('dismissed','hidden','deleted','user_warned')", name="ck_forum_flag_resolution"),
        Index("ix_forum_flags_open", "resolved_at", "created_at"),
    )
    id = Column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    post_id = Column(UUID(as_uuid=True), ForeignKey("forum_posts.id", ondelete="CASCADE"), nullable=False)
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    reason = Column(String(300), nullable=True)
    confidence = Column(Float, nullable=True)  # set when an automated check raised it
    source = Column(String(32), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    resolved_at = Column(DateTime(timezone=True), nullable=True)
    resolved_by_id = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    resolution = Column(String(12), nullable=True)


class ForumSubscription(Base):
    __tablename__ = "forum_subscriptions"
